// Converts JLCPCB impedance-template JSON (scripts/jlc/*.json, fetched from the
// public calculator API) into src/data/jlcStackups.ts.
// Usage: node scripts/build-jlc-stackups.mjs
import fs from 'node:fs';
import path from 'node:path';

const dir = path.resolve('scripts/jlc');
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.json'));
const out = [];
const bySignature = new Set();
const names = new Map();
const r4 = (v) => Math.round(Number(v) * 1e4) / 1e4;

for (const f of files.sort()) {
  const j = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  for (const t of j.body?.list ?? []) {
    const name = String(t.appointName ?? '');
    if (!/^JLC[0-9A-Z-]+$/.test(name)) continue; // skip "custom" placeholders
    const L = [];
    for (const b of t.basicDataList ?? []) {
      if (b.materialType === 1) {
        L.push(['c', b.layerName, r4(b.topConductorThick)]);
      } else if (b.materialType === 0) {
        L.push(['d', `Prepreg ${b.specificationsModel || ''}`.trim(), r4(b.dielectricThick), r4(b.dielectricConstant)]);
      } else if (b.materialType === 2) {
        const [a, c] = String(b.layerName).split('/');
        const m = /(\d+(?:\.\d+)?)\s*mm/.exec(String(b.materialName ?? ''));
        L.push(['c', a, r4(b.topConductorThick)]);
        L.push(['d', m ? `Core ${m[1]} mm` : 'Core', r4(b.dielectricThick), r4(b.dielectricConstant)]);
        L.push(['c', c, r4(b.botConductorThick)]);
      } else if (b.materialType === 3) {
        // core laminate without copper (filler between prepreg plies)
        L.push(['d', `Core ${r4(b.dielectricThick)} mm (no Cu)`, r4(b.dielectricThick), r4(b.dielectricConstant)]);
      }
    }
    if (!L.length) continue;
    const sig = JSON.stringify(L);
    if (bySignature.has(sig)) continue;
    bySignature.add(sig);
    const n = (names.get(name) ?? 0) + 1;
    names.set(name, n);
    const copper = L.filter((l) => l[0] === 'c').length;
    // JLC names encode layers and thickness: JLC04161H → 4 layers, 1.6 mm
    const m = /^JLC(\d{2})(\d{2})/.exec(name);
    const nominal = m && Number(m[1]) === copper ? Number(m[2]) / 10 : r4(t.plateThickness);
    out.push({ id: `jlc-${name.toLowerCase()}${n > 1 ? `-${n}` : ''}`, name: n > 1 ? `${name} (alt ${n})` : name, n: copper, nominal, L });
  }
}
out.sort((a, b) => a.n - b.n || a.nominal - b.nominal || a.name.localeCompare(b.name));

const header = `// Generated by scripts/build-jlc-stackups.mjs from JLCPCB's impedance-template data.
// Layer tuples: ['c', name, thickness_mm] copper | ['d', name, thickness_mm, er] dielectric.
/* eslint-disable */
export type RawLayer = ['c', string, number] | ['d', string, number, number];
export interface RawStackup { id: string; name: string; n: number; nominal: number; L: RawLayer[] }
export const JLC_FETCHED = '2026-09-22';
export const JLC_STACKUPS: RawStackup[] = `;
fs.mkdirSync('src/data', { recursive: true });
fs.writeFileSync('src/data/jlcStackups.ts', header + JSON.stringify(out) + ';\n');
const counts = {};
for (const s of out) counts[`${s.n}L ${s.nominal}mm`] = (counts[`${s.n}L ${s.nominal}mm`] ?? 0) + 1;
console.log(`${out.length} stackups`, counts);
